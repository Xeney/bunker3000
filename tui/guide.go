func (m *model) updateGuide(msg tea.KeyMsg) (tea.Model, tea.Cmd) {
	switch msg.String() {
	case "up", "k":
		if m.achieveChoice > 0 {
			m.achieveChoice--
		}
	case "down", "j":
		if m.achieveChoice < len(guidePages)-1 {
			m.achieveChoice++
		}
	case "esc", "q":
		m.screen = screenMenu
		m.menuChoice = 0
	}
	return m, nil
}

func (m *model) viewGuide() string {
	var lines []string
	for i, page := range guidePages {
		if i == m.achieveChoice {
			lines = append(lines, SelectedStyle.Render(fmt.Sprintf(" СТРАНИЦА %d/%d ", i+1, len(guidePages))))
			lines = append(lines, "")
			for _, line := range splitLines(page) {
				lines = append(lines, ValueStyle.Render(" "+line))
			}
		}
		lines = append(lines, "")
	}
	lines = append(lines, HelpStyle.Render("↑/↓ страницы · Esc назад"))

	body := lipgloss.JoinVertical(lipgloss.Left, lines...)
	return RenderInBox("РУКОВОДСТВО", body)
}

func splitLines(s string) []string {
	var result []string
	start := 0
	for i := 0; i < len(s); i++ {
		if s[i] == '\n' {
			result = append(result, s[start:i])
			start = i + 1
		}
	}
	if start < len(s) {
		result = append(result, s[start:])
	}
	return result
}
